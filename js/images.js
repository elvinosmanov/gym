const IMGU = "https://cdn.jsdelivr.net/gh/yuhonas/free-exercise-db@f00c92c7dcf1216a928a52c3706c7ce8e2f71ed5/exercises/";
/* İstifadəçidən (və ya idxal edilmiş yedəkdən / buluddan) gələn link yalnız
   http(s) ola bilər və atribut kontekstinə HƏMİŞƏ esc ilə yazılır — əks halda
   linkin içindəki dırnaq atributdan çıxıb hadisə (onerror və s.) əlavə edə bilər. */
function safeURL(u){
  try{ const x = new URL(String(u||"")); return (x.protocol==="http:" || x.protocol==="https:") ? x.href : ""; }
  catch(e){ return ""; }
}
function frames(ex){
  if(!ex) return [];
  if(ex.im && IMG[ex.im]) return IMG[ex.im].map(p => IMGU + p);
  if(ex.url) return [safeURL(ex.url)].filter(Boolean);   /* öz hərəkəti: birbaşa link */
  if(ex.file) return ["https://commons.wikimedia.org/wiki/Special:FilePath/"
                      + encodeURIComponent(String(ex.file).replace(/ /g,"_")) + "?width=500"];
  return [];
}
/* animasiyalı və ya tək kadrlı şəkil bloku — cls: "exanim" (böyük) / "exanim sm" (kiçik) */
function exImg(ex, cls){
  const f = frames(ex);
  if(!f.length) return `<div class="${cls} ph">🏋️</div>`;
  const alt = esc(ex.name||"");
  return `<div class="${cls}"><img src="${esc(f[0])}" alt="${alt}" loading="lazy" onerror="this.closest('.exanim').classList.add('ph')">${f[1]?`<img class="f2" src="${esc(f[1])}" alt="" loading="lazy" onerror="this.remove()">`:""}</div>`;
}
